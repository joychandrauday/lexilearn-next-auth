async function seedGREHighFrequency() {
  try {
    console.log('Connecting to MongoDB at:', mongoUri.replace(/:([^:@]{4})[^:@]*@/, ':****@'));
    await mongoose.connect(mongoUri);
    console.log('Connected to MongoDB successfully.');

    const db = mongoose.connection.db;
    const wordsCol = db.collection('words');
    const feedCol = db.collection('feedposts');

    let insertedWords = 0;
    let updatedWords = 0;
    let feedCreated = 0;

    for (const item of GRE_HIGH_FREQUENCY_WORDS) {
      const lowerWord = item.word.toLowerCase().trim();

      // Upsert into words collection
      const wordDoc = {
        word: lowerWord,
        bangla: item.bangla,
        meaning: item.meaning,
        partOfSpeech: item.partOfSpeech,
        intensity: item.intensity,
        exam: item.exam,
        examTags: item.examTags,
        frequencyCount: item.frequencyCount,
        isMostRepeated: item.isMostRepeated,
        verificationScore: item.verificationScore,
        verificationStatus: item.verificationStatus,
        verifiedBy: item.verifiedBy,
        upvotes: item.upvotes,
        downvotes: 0,
        example: item.example,
        synonyms: item.synonyms,
        antonyms: item.antonyms,
        mnemonic: item.mnemonic,
        contributedBy: 'Barron\'s 333 / Manhattan Prep GRE Elite Vault',
        userEmail: 'community@lexilearn.com',
        savedBy: ['community@lexilearn.com'],
        savedCount: item.upvotes || 50,
        reviewCount: 0,
        correctCount: 0,
        easeFactor: 2.5,
        interval: 1,
        nextReviewAt: new Date(),
        difficulty: 'good',
        updatedAt: new Date(),
      };

      const wordResult = await wordsCol.updateOne(
        { word: lowerWord },
        {
          $set: wordDoc,
          $setOnInsert: { createdAt: new Date() },
        },
        { upsert: true }
      );

      if (wordResult.upsertedCount > 0) {
        insertedWords++;
      } else {
        updatedWords++;
      }

      // Create or update matching FeedPost (vocab_card) for the single-stroke feed
      const feedTitle = `${item.word.toUpperCase()} • ${item.bangla}`;
      const feedContent = `${item.meaning}\n\n• উদাহরণ: ${item.example}\n• নেমোনিক: ${item.mnemonic}`;

      const feedDoc = {
        title: feedTitle,
        content: feedContent,
        type: 'vocab_card',
        tags: [...item.examTags, 'GRE High Frequency', item.partOfSpeech],
        category: item.exam === 'bank' ? 'bank' : 'bcs',
        difficulty: item.intensity === 'high' ? 'hard' : 'medium',
        author: {
          name: 'লেক্সিবট GRE হাব',
          email: 'lexibot@lexilearn.com',
          avatar: '',
          role: 'lexibot',
        },
        vocabData: {
          word: item.word,
          meaning: item.meaning,
          bangla: item.bangla,
          mnemonic: item.mnemonic,
          partOfSpeech: item.partOfSpeech,
          exampleSentence: item.example,
          examTags: item.examTags,
        },
        likes: item.upvotes || 45,
        likedBy: [],
        bookmarks: Math.round((item.upvotes || 45) / 2),
        bookmarkedBy: [],
        viewsCount: (item.upvotes || 45) * 6,
        isPinned: false,
        updatedAt: new Date(),
      };

      const feedResult = await feedCol.updateOne(
        { 'vocabData.word': item.word },
        {
          $set: feedDoc,
          $setOnInsert: { createdAt: new Date() },
        },
        { upsert: true }
      );

      if (feedResult.upsertedCount > 0) {
        feedCreated++;
      }
    }

    console.log('Seeding Summary:');
    console.log(`- Total GRE High Frequency Words processed: ${GRE_HIGH_FREQUENCY_WORDS.length}`);
    console.log(`- New words inserted: ${insertedWords}`);
    console.log(`- Existing words enriched & updated: ${updatedWords}`);
    console.log(`- New Feed Posts created for Reel Feed: ${feedCreated}`);

    const finalWordCount = await wordsCol.countDocuments();
    const finalFeedCount = await feedCol.countDocuments();
    console.log(`- Final Database Totals: ${finalWordCount} words, ${finalFeedCount} feedposts.`);

    await mongoose.disconnect();
    console.log('Database connection closed.');
    process.exit(0);
  } catch (err) {
    console.error('Error seeding GRE High Frequency words:', err);
    process.exit(1);
  }
}

seedGREHighFrequency();
